// Double-dispatch interface for operations over the AST hierarchy.
// Adding a concrete AST node requires adding a Visit overload here, so visitors
// fail at compile time instead of silently falling through a runtime type chain.
class ASTVisitor {
public:
  virtual ~ASTVisitor() = default;

  virtual std::string Visit(const ArrayDimensionsAST& node) = 0;
  virtual std::string Visit(const CompUnitAST& node) = 0;
  virtual std::string Visit(const CompUnitSequenceAST& node) = 0;
  virtual std::string Visit(const CompUnitListAST& node) = 0;
  virtual std::string Visit(const FunctionDefinitionUnitAST& node) = 0;
  virtual std::string Visit(const DeclarationUnitAST& node) = 0;
  virtual std::string Visit(const FuncDefAST& node) = 0;
  virtual std::string Visit(const FuncFParamAST& node) = 0;
  virtual std::string Visit(const FuncFParamsAST& node) = 0;
  virtual std::string Visit(const DeclBlockAST& node) = 0;
  virtual std::string Visit(const StmtBlockAST& node) = 0;
  virtual std::string Visit(const BlockAST& node) = 0;
  virtual std::string Visit(const UnmatchedStmtWrapperAST& node) = 0;
  virtual std::string Visit(const MatchedStmtWrapperAST& node) = 0;
  virtual std::string Visit(const IfUnmatchedStmtAST& node) = 0;
  virtual std::string Visit(const IfElseUnmatchedStmtAST& node) = 0;
  virtual std::string Visit(const ReturnStmtAST& node) = 0;
  virtual std::string Visit(const AssignStmtAST& node) = 0;
  virtual std::string Visit(const ExpStmtAST& node) = 0;
  virtual std::string Visit(const EmptyStmtAST& node) = 0;
  virtual std::string Visit(const BlockStmtAST& node) = 0;
  virtual std::string Visit(const IfMatchedStmtAST& node) = 0;
  virtual std::string Visit(const WhileStmtAST& node) = 0;
  virtual std::string Visit(const ContinueStmtAST& node) = 0;
  virtual std::string Visit(const BreakStmtAST& node) = 0;
  virtual std::string Visit(const ExpAST& node) = 0;
  virtual std::string Visit(const UnaryOPExpAST& node) = 0;
  virtual std::string Visit(const PrimaryUnaryExpAST& node) = 0;
  virtual std::string Visit(const FuncCallExpAST& node) = 0;
  virtual std::string Visit(const FuncRParamsAST& node) = 0;
  virtual std::string Visit(const ParenthesizedExprAST& node) = 0;
  virtual std::string Visit(const LValuePrimaryExprAST& node) = 0;
  virtual std::string Visit(const NumberPrimaryExprAST& node) = 0;
  virtual std::string Visit(const OpAST& node) = 0;
  virtual std::string Visit(const UnaryMulExpAST& node) = 0;
  virtual std::string Visit(const BinaryMulExprAST& node) = 0;
  virtual std::string Visit(const MulAddExpAST& node) = 0;
  virtual std::string Visit(const BinaryAddExprAST& node) = 0;
  virtual std::string Visit(const AddRelExpAST& node) = 0;
  virtual std::string Visit(const BinaryRelExprAST& node) = 0;
  virtual std::string Visit(const RelEqExpAST& node) = 0;
  virtual std::string Visit(const BinaryEqExprAST& node) = 0;
  virtual std::string Visit(const EqLAndExpAST& node) = 0;
  virtual std::string Visit(const BinaryLogicalAndExprAST& node) = 0;
  virtual std::string Visit(const LAndLOrExpAST& node) = 0;
  virtual std::string Visit(const BinaryLogicalOrExprAST& node) = 0;
  virtual std::string Visit(const LValAST& node) = 0;
  virtual std::string Visit(const ConstExpAST& node) = 0;
  virtual std::string Visit(const ConstDefAST& node) = 0;
  virtual std::string Visit(const ArrayConstDefAST& node) = 0;
  virtual std::string Visit(const ConstExpConstInitValAST& node) = 0;
  virtual std::string Visit(const ConstInitValListAST& node) = 0;
  virtual std::string Visit(const CompoundConstInitValueAST& node) = 0;
  virtual std::string Visit(const ConstDeclWrapperAST& node) = 0;
  virtual std::string Visit(const VarDeclWrapperAST& node) = 0;
  virtual std::string Visit(const ConstDeclAST& node) = 0;
  virtual std::string Visit(const ConstDefListAST& node) = 0;
  virtual std::string Visit(const VarDeclAST& node) = 0;
  virtual std::string Visit(const VarDefListAST& node) = 0;
  virtual std::string Visit(const SimpleVarDefAST& node) = 0;
  virtual std::string Visit(const InitializedVarDefAST& node) = 0;
  virtual std::string Visit(const ArrayVarDefAST& node) = 0;
  virtual std::string Visit(const ArrayInitializedVarDefAST& node) = 0;
  virtual std::string Visit(const InitValAST& node) = 0;
  virtual std::string Visit(const InitValListAST& node) = 0;
};
